"""Builds a class-armour dye mask from the client's own body texture: src/Ro3Emu.ClientHooks/ClassArmourMask.<Name>.cs.

    python -I tools/dyes/build-armour-mask.py <client dir> <texture> <Name> x,y [x,y ...]

The texture is read from the client's asset VFS (needs UnityPy; GEM11 apps/solro3/scripts/ro3vfs.py reads the VFS,
pass its folder in RO3VFS_DIR). From each seed point (texture pixels, top-down) the mask grows over the maroon cloth:
red hue, saturated, not too light (skin is paler), not metal (the atlas alpha marks metal). It stops at gold trim,
white edging, skin and other islands; creases enclosed by the cloth are filled. Only the generated rectangles ship:
no publisher texture is stored. Check a new mask in a dyed preview and in game before enabling its body.
"""
import os
import sys
from collections import deque

import numpy as np
from PIL import Image

sys.path.insert(0, os.environ.get("RO3VFS_DIR", "."))
from ro3vfs import Vfs  # noqa: E402

SIZE = 512


def cloth(im):
    alpha = np.array(im.getchannel("A"))
    hsv = np.array(im.convert("RGB").convert("HSV")).astype(int)
    h, s, v = hsv[..., 0], hsv[..., 1], hsv[..., 2]
    return ((h >= 232) | (h <= 12)) & (s >= 88) & (v >= 35) & (v <= 215) & (alpha < 128), h, s, alpha


def grow(ok, seeds):
    mask = np.zeros(ok.shape, bool)
    for x, y in seeds:
        if not ok[y, x]:
            raise SystemExit(f"seed {x},{y} is not cloth")
        q = deque([(y, x)])
        mask[y, x] = True
        while q:
            cy, cx = q.popleft()
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = cy + dy, cx + dx
                if 0 <= ny < SIZE and 0 <= nx < SIZE and ok[ny, nx] and not mask[ny, nx]:
                    mask[ny, nx] = True
                    q.append((ny, nx))
    return mask


def fill_creases(mask, h, s, alpha):
    outside = np.zeros(mask.shape, bool)
    q = deque()
    for i in range(SIZE):
        for p in ((0, i), (SIZE - 1, i), (i, 0), (i, SIZE - 1)):
            if not mask[p] and not outside[p]:
                outside[p] = True
                q.append(p)
    while q:
        y, x = q.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = y + dy, x + dx
            if 0 <= ny < SIZE and 0 <= nx < SIZE and not mask[ny, nx] and not outside[ny, nx]:
                outside[ny, nx] = True
                q.append((ny, nx))
    gold = (h >= 20) & (h <= 50) & (s >= 90)
    return mask | (~mask & ~outside & (alpha < 128) & ~gold)


def rectangles(mask):
    """Row runs merged downwards while they repeat: exact, no pixel outside the mask."""
    out, open_ = [], {}
    for y in range(SIZE + 1):
        runs = []
        if y < SIZE:
            x = 0
            while x < SIZE:
                if mask[y, x]:
                    start = x
                    while x < SIZE and mask[y, x]:
                        x += 1
                    runs.append((start, x - 1))
                else:
                    x += 1
        nxt = {r: open_.pop(r, y) for r in runs}
        out += [(r[0], y0, r[1], y - 1) for r, y0 in open_.items()]
        open_ = nxt
    return sorted(out, key=lambda r: (r[1], r[0]))


def main():
    client, texture, name, *points = sys.argv[1:]
    im = Vfs(os.path.join(client, "ro3_Data", "StreamingAssets", "VFS")).image(texture + ".png")
    if im is None or im.size != (SIZE, SIZE):
        raise SystemExit(f"{texture}.png not found or not {SIZE}x{SIZE}")
    ok, h, s, alpha = cloth(im.convert("RGBA"))
    mask = fill_creases(grow(ok, [tuple(int(c) for c in p.split(",")) for p in points]), h, s, alpha)
    rects = rectangles(mask)
    body = ",\n".join("        " + ", ".join(f"{a}, {b}, {c}, {d}" for a, b, c, d in rects[i:i + 6]) for i in range(0, len(rects), 6))
    path = os.path.join(os.path.dirname(__file__), "..", "..", "src", "Ro3Emu.ClientHooks", f"ClassArmourMask.{name}.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""namespace Ro3Emu.ClientHooks;

// Generated by tools/dyes/build-armour-mask.py from {texture} (seeds {' '.join(points)}): {len(rects)} rectangles,
// {int(mask.sum())} cloth texels. x0, y0, x1, y1 inclusive, in top-down texels of the {SIZE}x{SIZE} atlas.
internal static partial class ClassArmourMask
{{
    private static readonly short[] {name} =
    {{
{body}
    }};
}}
""")
    print(f"{path}: {len(rects)} rectangles, {int(mask.sum())} texels")


if __name__ == "__main__":
    main()
